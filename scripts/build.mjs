/**
 * Build a distributable tarball with a tamper-evidence manifest.
 *
 * Steps: copy exactly what `package.json#files` names into a staging directory,
 * hash every shipped runtime file into `integrity.json`, pack the staging
 * directory, and drop the tarball into `dist/`.
 *
 * The manifest deliberately does NOT belong to the source checkout: a linked
 * development install must never be flagged as tampered just because its files
 * are being edited.
 *
 * Usage: node scripts/build.mjs <path-to-pnpm.mjs>
 */

import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import {
  copyFileSync, mkdirSync, readFileSync, readdirSync, renameSync, rmSync, writeFileSync,
} from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const pnpmPath = process.argv[2]
if (!pnpmPath) {
  console.error('usage: node scripts/build.mjs <path-to-pnpm.mjs>')
  process.exit(2)
}

const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
const distDir = join(root, 'dist')
const stage = join(distDir, '.stage')

/** Escape one literal segment for use inside a RegExp. */
const escapeSegment = (value) => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')

/** Copy one `files` pattern into the staging directory; returns staged paths. */
function stagePattern(pattern) {
  const slash = pattern.lastIndexOf('/')
  const dir = slash >= 0 ? pattern.slice(0, slash) : ''
  const base = slash >= 0 ? pattern.slice(slash + 1) : pattern
  const staged = []
  if (!base.includes('*')) {
    const relative = dir ? `${dir}/${base}` : base
    mkdirSync(join(stage, dir), { recursive: true })
    copyFileSync(join(root, relative), join(stage, relative))
    return [relative]
  }
  const matcher = new RegExp(`^${base.split('*').map(escapeSegment).join('.*')}$`)
  for (const name of readdirSync(join(root, dir))) {
    if (!matcher.test(name)) continue
    mkdirSync(join(stage, dir), { recursive: true })
    copyFileSync(join(root, dir, name), join(stage, dir, name))
    staged.push(dir ? `${dir}/${name}` : name)
  }
  return staged
}

rmSync(stage, { recursive: true, force: true })
mkdirSync(stage, { recursive: true })

const shipped = []
for (const pattern of pkg.files || []) {
  // `integrity.json` is generated by this script, not copied from the checkout.
  if (pattern === 'integrity.json') continue
  shipped.push(...stagePattern(pattern))
}
// npm always ships the manifest; copy it, but do NOT hash it: the packer rewrites
// package.json while producing the tarball (field normalisation), so a digest
// taken from the staging copy would never match the packed file.
copyFileSync(join(root, 'package.json'), join(stage, 'package.json'))

const files = {}
for (const relative of shipped) {
  files[relative] = createHash('sha256').update(readFileSync(join(stage, relative))).digest('hex')
}
writeFileSync(
  join(stage, 'integrity.json'),
  `${JSON.stringify({
    name: pkg.name,
    version: pkg.version,
    algorithm: 'sha256',
    generatedAt: new Date().toISOString(),
    files,
  }, null, 2)}\n`,
)

mkdirSync(distDir, { recursive: true })
execFileSync(process.execPath, [pnpmPath, 'pack'], { cwd: stage, stdio: 'inherit' })

const tarball = readdirSync(stage).find((name) => name.endsWith('.tgz'))
if (!tarball) {
  console.error('build failed: pnpm pack produced no tarball')
  rmSync(stage, { recursive: true, force: true })
  process.exit(1)
}
const target = join(distDir, tarball)
rmSync(target, { force: true })
renameSync(join(stage, tarball), target)
rmSync(stage, { recursive: true, force: true })

const shippedCount = Object.keys(files).length
console.log(`built ${target}`)
console.log(`manifest covers ${shippedCount} files`)
